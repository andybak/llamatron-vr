"""Export the original SB sample descriptors and byte-exact unsigned PCM WAV assets."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import wave


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=Path('.tools/ci-game-input'))
    parser.add_argument('--reference-memory', type=Path, help='Captured bank plus observed overread tail; prefix must match SPL exactly')
    parser.add_argument('--output', type=Path, default=Path('standalone/Unity/Assets/Llamatron/Resources/Generated/Audio'))
    parser.add_argument('--csharp', type=Path, default=Path('standalone/Unity/Assets/Llamatron/Core/OriginalSoundData.cs'))
    parser.add_argument('--report', type=Path, default=Path('artifacts/reconstruction/audio-assets.json'))
    args = parser.parse_args()
    driver = (args.source / 'SBLASTER.BIN').read_bytes()
    bank = (args.source / 'LLATRON.SPL').read_bytes()
    if sha(driver) != '974cd3d53ba1bb6c621ba0a5168c5e5df18bd4846b58fd2b7dd856c925b1fcda':
        parser.error('Sound driver differs from the analyzed revision')
    if sha(bank) != '8d9a5f3ad8fa527272a8b1f4fd492834d319a03d730a131733c635433ef47a31':
        parser.error('Sample bank differs from the analyzed revision')
    memory = args.reference_memory.read_bytes() if args.reference_memory else bank
    if memory[:len(bank)] != bank:
        parser.error('Reference memory prefix does not match the complete original SPL')
    base_hz = 8000  # Container rate; playback pitch uses the original DSP time constant.
    args.output.mkdir(parents=True, exist_ok=True)
    records = []
    for sample in range(1, 33):
        offset, frames, loop_offset, loop_length = struct.unpack_from('<IHHH', driver, 0x609 + (sample + 1) * 10)
        if loop_offset or loop_length:
            parser.error(f'Sample {sample} has unhandled loop descriptor words')
        if not frames or offset + frames > len(memory):
            parser.error(f'Sample {sample} requires {max(0, offset + frames - len(bank))} observed tail bytes; supply --reference-memory from probe_reference_audio.py')
        pcm = memory[offset:offset + frames]
        # Web builds use these exact unsigned bytes instead of AAC-transcoded clips.
        (args.output / f'sample-{sample:02d}-pcm.bytes').write_bytes(pcm)
        target = args.output / f'sample-{sample:02d}.wav'
        with wave.open(str(target), 'wb') as writer:
            writer.setparams((1, 1, base_hz, 0, 'NONE', 'not compressed'))
            writer.writeframes(pcm)
        with wave.open(str(target), 'rb') as reader:
            if reader.readframes(frames) != pcm or reader.getnframes() != frames:
                raise ValueError(f'WAV verification failed for sample {sample}')
        records.append({'id': sample, 'offset': offset, 'frames': frames, 'pcm_sha256': sha(pcm),
                        'observed_tail_bytes': max(0, offset + frames - len(bank)), 'wav': target.as_posix()})
    constants = list(driver[0x3d2:0x3d7])
    report = {'driver_sha256': sha(driver), 'bank_sha256': sha(bank), 'bank_bytes': len(bank),
              'format': 'unsigned 8-bit mono PCM', 'container_hz': base_hz,
              'dsp_time_constants': constants, 'nominal_rates_hz': [1_000_000 / (256 - value) for value in constants],
              'reference_memory': str(args.reference_memory) if args.reference_memory else None,
              'reference_memory_sha256': sha(memory),
              'tail_limitation': 'Sample 30 includes 96 bytes observed beyond the SPL in one original DOS allocation layout; other layouts may differ.',
              'dsp_reference': 'https://dosbox-x.com/doxygen/html/sblaster_8cpp_source.html#l01716', 'samples': records}
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(f'{json.dumps(report, indent=2)}\n')
    lines = ['// Generated by tools/recover_audio.py; descriptor data, not DOS instructions.',
             'namespace Llamatron.Core', '{', '    public static class OriginalSoundData', '    {',
             f'        public const int ContainerHz = {base_hz};',
             f'        public const string DriverSha256 = "{sha(driver)}";',
             f'        public const string BankSha256 = "{sha(bank)}";']
    for name, kind, values in [('Offsets', 'int', [r['offset'] for r in records]),
                               ('Frames', 'int', [r['frames'] for r in records]),
                               ('TimeConstants', 'byte', constants)]:
        payload = ', '.join(str(value) for value in values)
        lines.extend([f'        public static System.Collections.Generic.IReadOnlyList<{kind}> {name} {{ get; }} =',
                      f'            System.Array.AsReadOnly(new {kind}[] {{ {payload} }});'])
    lines.extend(['    }', '}', ''])
    args.csharp.parent.mkdir(parents=True, exist_ok=True)
    args.csharp.write_text('\n'.join(lines))
    print(f'[LLAUDIO] Exported and verified {len(records)} mono PCM WAVs; sample 30 uses an explicit observed 96-byte tail profile.')


if __name__ == '__main__':
    main()
