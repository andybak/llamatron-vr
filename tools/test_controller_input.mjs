import assert from 'node:assert/strict';
import {controllerBits,controllerSources} from '../viewer/controller-input.js';
const source=(hand,axes,mapping='xr-standard')=>({handedness:hand,gamepad:{axes,mapping,buttons:[{pressed:false}]}});
assert.equal(controllerBits([source('left',[0,0,1,0])]),8);
assert.equal(controllerBits([source('right',[0,0,-1,0])]),4);
assert.equal(controllerBits([source('left',[0,0,0,-1,0,0])]),1);
assert.equal(controllerBits([source('none',[0,1])]),2);
assert.equal(controllerBits([source('left',[0,0,.1,-.1])]),0);
assert.equal(controllerBits([source('left',[0,0,0,0]),source('right',[0,0,1,-1])]),9);
const left=source('left',[0,0,-.4,0]), right=source('right',[0,0,1,0]);
assert.equal(controllerBits([right,left]),4,'Active left stick takes priority regardless of source order');
assert.equal(controllerBits([left,right]),4);
assert.equal(controllerBits([right]),8,'Right works while left is absent');
assert.equal(controllerBits([right,left]),4,'Returning left immediately regains movement');
assert.equal(controllerBits([]),0,'Removing both releases movement');
assert.equal(controllerBits([{handedness:'left'},right]),8,'Left without a gamepad does not block right');
assert.equal(controllerBits(controllerSources([right],[left],20)),4,'Native left recovers browser omission');
assert.equal(controllerBits(controllerSources([right],[left],300)),8,'Expired native input is released');
assert.equal(controllerSources([left,right],[left],20).length,2,'Do not duplicate a hand');
console.log('Controller checks passed: axis mapping, left priority, disconnect/reconnect and release.');
